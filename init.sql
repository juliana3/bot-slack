CREATE TABLE IF NOT EXISTS public.new_entrants (
    id SERIAL PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    dni VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL UNIQUE,
    phone_number VARCHAR(20) NOT NULL,
    address VARCHAR(255) NOT NULL,
    locality VARCHAR(100) NOT NULL,
    date_of_birth VARCHAR(20) NOT NULL,
    health_insurance VARCHAR(100) NOT NULL,
    afip_code VARCHAR(50),
    cbu VARCHAR(50),
    alias VARCHAR(100),
    cuil VARCHAR(50),
    national_bank VARCHAR(100),
    national_account_number VARCHAR(100),
    bank_name VARCHAR(100),
    bank_address VARCHAR(255),
    swift_code VARCHAR(50),
    account_holder VARCHAR(100),
    account_number VARCHAR(50),
    routing_number VARCHAR(50),
    account_type VARCHAR(50),
    zip_code VARCHAR(20),
    type_of_contract VARCHAR(50) NOT NULL,
    dni_front TEXT NOT NULL,
    dni_back TEXT NOT NULL,
    onboarding_status VARCHAR(50) DEFAULT 'NoAutorizado',
    id_pf VARCHAR(50),
    pdf_status VARCHAR(50) DEFAULT 'NoAutorizado',
    id_drive_folder VARCHAR(50),
    created_at DATE NOT NULL
);